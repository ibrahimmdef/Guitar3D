import { useTexture } from '@react-three/drei';
import type { GuitarProfile } from '@guitar3d/shared';

export const DEFAULT_PROFILE_URL = '/guitar/veston.profile.json';

/** Texture URLs of a profile (fretboard + inlay mask, headstock face, rosette, body top). */
export function profileTextureUrls(p: GuitarProfile) {
  return [p.textures.fretboard?.url, p.textures.fretboard?.inlayMask, p.textures.headstock, p.textures.rosette, p.textures.bodyTop].filter((u): u is string => !!u);
}

/** Starts downloading/decoding the textures so the guitar can render in one go. */
export function preloadProfile(p: GuitarProfile) {
  for (const url of profileTextureUrls(p)) useTexture.preload(url);
}

/** Loads the owner's Veston profile (measured by scripts/measure-veston.py) and preloads its textures. */
export async function loadDefaultProfile(): Promise<GuitarProfile> {
  const r = await fetch(DEFAULT_PROFILE_URL);
  if (!r.ok) throw new Error(`Gitar profili yüklenemedi (${r.status})`);
  const p = (await r.json()) as GuitarProfile;
  preloadProfile(p);
  return p;
}

export const TEMPLATES_INDEX_URL = '/guitar/templates/index.json';

/** Row of /guitar/templates/index.json (generated by scripts/gen-guitar-templates.ts). */
export interface GuitarTemplateEntry {
  id: string;
  name: string;
  description: string;
  /** Family label shown in the UI ('Dreadnought', 'Klasik', …). */
  kind: string;
  profileUrl: string;
}

/** The guitar templates shipped with the app (empty when the index is missing or malformed). */
export async function listGuitarTemplates(f: typeof fetch = (...a) => fetch(...a)): Promise<GuitarTemplateEntry[]> {
  try {
    const r = await f(TEMPLATES_INDEX_URL);
    if (!r.ok) return [];
    const list = JSON.parse(await r.text()) as unknown;
    return Array.isArray(list) ? list.filter((t): t is GuitarTemplateEntry => !!t && typeof t.id === 'string' && typeof t.profileUrl === 'string') : [];
  } catch {
    return [];
  }
}

/** Loads any GuitarProfile JSON (a template, the Veston, a saved guitar) and preloads its textures. */
export async function loadGuitarProfile(url: string): Promise<GuitarProfile> {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`Gitar profili yüklenemedi (${r.status})`);
  const p = (await r.json()) as GuitarProfile;
  if (!p || !Array.isArray(p.body?.outline)) throw new Error('Geçersiz gitar profili');
  preloadProfile(p);
  return p;
}
